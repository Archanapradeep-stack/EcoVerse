import { PrismaClient } from '@prisma/client';

const prisma = new PrismaClient();

async function main() {
  console.log('Seeding database with EcoVerse content...');

  // Clear existing courses (for developmen
  // t)
  await prisma.quizResult.deleteMany();
  await prisma.courseProgress.deleteMany();
  await prisma.question.deleteMany();
  await prisma.quiz.deleteMany();
  await prisma.lesson.deleteMany();
  await prisma.course.deleteMany();

  // 1. Create Courses
  const climateCourse = await prisma.course.create({
    data: {
      title: 'Climate Change Fundamentals',
      description: 'Understand the science behind climate change, its global impacts, and what we can do to mitigate it.',
      category: 'Climate Change',
      difficulty: 'Beginner',
      duration: '45 mins',
      thumbnail: 'https://images.unsplash.com/photo-1542601906990-b4d3fb778b09?w=800&auto=format&fit=crop&q=60',
    }
  });

  const wasteCourse = await prisma.course.create({
    data: {
      title: 'Zero Waste Lifestyle',
      description: 'Practical steps to reduce your daily waste, learn proper recycling, and embrace a sustainable lifestyle.',
      category: 'Waste Management',
      difficulty: 'Intermediate',
      duration: '1.5 hrs',
      thumbnail: 'https://images.unsplash.com/photo-1532996122724-e3c354a0b15b?w=800&auto=format&fit=crop&q=60',
    }
  });

  const energyCourse = await prisma.course.create({
    data: {
      title: 'Renewable Energy 101',
      description: 'Explore solar, wind, and hydro power. Learn how renewable energy is reshaping the global power grid.',
      category: 'Renewable Energy',
      difficulty: 'Beginner',
      duration: '1 hr',
      thumbnail: 'https://images.unsplash.com/photo-1466611653911-95081537e5b7?w=800&auto=format&fit=crop&q=60',
    }
  });

  // 2. Create Lessons for Climate Course
  const lesson1 = await prisma.lesson.create({
    data: {
      courseId: climateCourse.id,
      title: 'The Greenhouse Effect',
      order: 1,
      content: JSON.stringify({
        blocks: [
          { type: 'text', content: 'The greenhouse effect is a natural process that warms the Earth\'s surface. When the Sun\'s energy reaches the Earth\'s atmosphere, some of it is reflected back to space and the rest is absorbed and re-radiated by greenhouse gases.' },
          { type: 'image', url: 'https://images.unsplash.com/photo-1473448912268-2022ce9509d8?w=800&auto=format&fit=crop&q=60', caption: 'Earth atmosphere' },
          { type: 'text', content: 'Human activities, particularly the burning of fossil fuels, are increasing the concentrations of greenhouse gases, amplifying the natural greenhouse effect and leading to global warming.' }
        ]
      })
    }
  });

  const lesson2 = await prisma.lesson.create({
    data: {
      courseId: climateCourse.id,
      title: 'Carbon Footprint',
      order: 2,
      content: JSON.stringify({
        blocks: [
          { type: 'text', content: 'A carbon footprint is the total amount of greenhouse gases (including carbon dioxide and methane) that are generated by our actions.' },
          { type: 'text', content: 'The average carbon footprint for a person in the United States is 16 tons, one of the highest rates in the world. Globally, the average is closer to 4 tons.' }
        ]
      })
    }
  });

  // 3. Create Quiz for Lesson 1 (Climate Course)
  const quiz1 = await prisma.quiz.create({
    data: {
      lessonId: lesson1.id,
      xpReward: 100,
      coinReward: 50
    }
  });

  await prisma.question.createMany({
    data: [
      {
        quizId: quiz1.id,
        questionText: 'What is the primary cause of the amplified greenhouse effect today?',
        options: ['Volcanic eruptions', 'Solar flares', 'Burning fossil fuels', 'Deforestation only'],
        correctAnswer: 2,
        topic: 'Greenhouse Effect'
      },
      {
        quizId: quiz1.id,
        questionText: 'Which of these is NOT a primary greenhouse gas?',
        options: ['Carbon Dioxide', 'Methane', 'Oxygen', 'Water Vapor'],
        correctAnswer: 2,
        topic: 'Greenhouse Gases'
      },
      {
        quizId: quiz1.id,
        questionText: 'What happens to the Earth\'s surface temperature when greenhouse gases increase?',
        options: ['It cools down', 'It stays exactly the same', 'It warms up', 'It fluctuates randomly'],
        correctAnswer: 2,
        topic: 'Global Warming'
      },
      {
        quizId: quiz1.id,
        questionText: 'Which sector contributes most to global greenhouse gas emissions?',
        options: ['Agriculture', 'Transportation', 'Energy/Electricity', 'Waste'],
        correctAnswer: 2,
        topic: 'Emissions'
      },
      {
        quizId: quiz1.id,
        questionText: 'What is the most abundant greenhouse gas in the atmosphere?',
        options: ['Carbon Dioxide', 'Methane', 'Water Vapor', 'Nitrous Oxide'],
        correctAnswer: 2,
        topic: 'Greenhouse Gases'
      }
    ]
  });

  // 4. Create Quiz for Lesson 2
  const quiz2 = await prisma.quiz.create({
    data: {
      lessonId: lesson2.id,
      xpReward: 100,
      coinReward: 50
    }
  });

  await prisma.question.createMany({
    data: [
      {
        quizId: quiz2.id,
        questionText: 'What does a "carbon footprint" measure?',
        options: ['Size of your feet', 'Amount of oxygen you breathe', 'Total greenhouse gases generated by your actions', 'Amount of plants in your garden'],
        correctAnswer: 2,
        topic: 'Carbon Footprint'
      }
    ]
  });

  console.log('Database seeded successfully!');
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
